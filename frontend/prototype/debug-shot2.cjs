const fs = require('node:fs');
const PORT = '9223';
const BASE = 'file:///E:/dsh_home/workspaces/agent/frontend/prototype/index.html';
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const url = `${BASE}?state=normal`;
  const created = await (await fetch(`http://127.0.0.1:${PORT}/json/new?${encodeURIComponent(url)}`, { method: 'PUT' })).json();
  const ws = new WebSocket(created.webSocketDebuggerUrl);
  let id = 0; const pending = new Map();
  ws.onmessage = ev => { const m = JSON.parse(ev.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
  await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
  const cmd = (method, params = {}) => new Promise((resolve, reject) => { const i = ++id; pending.set(i, m => m.error ? reject(new Error(m.error.message)) : resolve(m.result)); ws.send(JSON.stringify({ id: i, method, params })); });
  const ev = async (expression) => (await cmd('Runtime.evaluate', { expression, awaitPromise: true, returnByValue: true })).result?.value;
  await cmd('Page.enable');
  await cmd('Emulation.setDeviceMetricsOverride', { width: 1600, height: 1000, deviceScaleFactor: 1, mobile: false });
  await sleep(1500);
  console.log('state', await ev('document.body.dataset.state'));
  await ev("document.getElementById('overlay').hidden = true; 'ok'");
  await sleep(400);
  const s = await cmd('Page.captureScreenshot', { format: 'png' });
  fs.writeFileSync('E:/dsh_home/workspaces/agent/frontend/prototype/shots/y-normal-1600.png', Buffer.from(s.data, 'base64'));
  console.log('saved', fs.statSync('E:/dsh_home/workspaces/agent/frontend/prototype/shots/y-normal-1600.png').size);
  ws.close();
})().catch(e => { console.error('ERR', e.message); process.exit(1); });
