const PORT = '9223';
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  const created = await (await fetch(`http://127.0.0.1:${PORT}/json/new?${encodeURIComponent('http://127.0.0.1:8897/')}`, { method: 'PUT' })).json();
  const ws = new WebSocket(created.webSocketDebuggerUrl);
  let id = 0; const pending = new Map();
  ws.onmessage = e => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
  await new Promise((r, j) => { ws.onopen = r; ws.onerror = j; });
  const cmd = (method, params = {}) => new Promise((res, rej) => { const i = ++id; pending.set(i, m => m.error ? rej(new Error(m.error.message)) : res(m.result)); ws.send(JSON.stringify({ id: i, method, params })); });
  const ev = async s => (await cmd('Runtime.evaluate', { expression: s, returnByValue: true })).result.value;
  await cmd('Page.enable');
  await cmd('Emulation.setDeviceMetricsOverride', { width: 1600, height: 1000, deviceScaleFactor: 1, mobile: false });
  await sleep(900);
  console.log('before', await ev('window.scrollY'));
  const clicked = await ev(`(() => { const a=[...document.querySelectorAll('.g-nav a')].find(x=>x.textContent.includes('任务栈')); if(!a) return 'nf'; a.click(); return 'ok'; })()`);
  await sleep(900);
  console.log('click', clicked, 'after', await ev('window.scrollY'));
  console.log('target', await ev(`(() => { const el=document.getElementById('taskstack'); if(!el) return 'nf'; const r=el.getBoundingClientRect(); return JSON.stringify({top:Math.round(r.top), y:Math.round(window.scrollY)}); })()`));
  ws.close();
})().catch(e => { console.error('ERR', e.message); process.exit(1); });
